"""Canonical filesystem locations for figures and result artefacts.

Why this module exists
----------------------
Hard-coding paths like ``"../../results"`` inside task modules makes them
fragile: they break the moment a script is run from a different working
directory. This module resolves every path relative to the *package file*
(``__file__``), so the tasks work regardless of the current directory, and
from both editable and wheel installs.

Layout assumptions
------------------
The package lives in a ``src``-layout repository::

    <repo_root>/
    ├── pyproject.toml       <- anchor used to detect the repo root
    ├── results/
    ├── report/
    │   └── figures/
    └── src/
        └── bit2118/
            └── paths.py

If, for any reason, the anchor file (``pyproject.toml``) is not found
two levels up, we fall back to the current working directory. This keeps
the package usable inside a wheel install, where the source tree is not
present.
"""

from __future__ import annotations

from pathlib import Path

__all__ = [
    "FIGURES_DIR",
    "PACKAGE_DIR",
    "REPORT_DIR",
    "REPO_ROOT",
    "RESULTS_DIR",
    "SRC_DIR",
    "ensure_dirs",
]


def _detect_repo_root() -> Path:
    """Return the repository root, resolved robustly.

    The function tries two strategies in order:

    1. **Anchor detection.** Walk up from this file and pick the first
       directory containing ``pyproject.toml``. This is the correct result
       for a normal ``src``-layout checkout.
    2. **Working directory fallback.** If no anchor is found (e.g. the
       package was installed non-editably and the source tree is gone),
       use :func:`pathlib.Path.cwd`. Callers get a valid, writable path
       rather than an exception.

    Returns
    -------
    pathlib.Path
        Absolute path to the repository root.
    """
    # Anchor search: at most four levels up from this file.
    here = Path(__file__).resolve()
    for candidate in here.parents:
        if (candidate / "pyproject.toml").is_file():
            return candidate
    # Fallback — the caller may still be inside the intended tree.
    return Path.cwd().resolve()


# -----------------------------------------------------------------------------
# Resolved locations
# -----------------------------------------------------------------------------
REPO_ROOT: Path = _detect_repo_root()
"""Absolute path to the repository root."""

SRC_DIR: Path = REPO_ROOT / "src"
"""Absolute path to the ``src`` directory."""

PACKAGE_DIR: Path = Path(__file__).resolve().parent
"""Absolute path to this package (``src/bit2118``)."""

RESULTS_DIR: Path = REPO_ROOT / "results"
"""Where JSON result files are written."""

REPORT_DIR: Path = REPO_ROOT / "report"
"""Where the written report and its source live."""

FIGURES_DIR: Path = REPORT_DIR / "figures"
"""Where plots generated by task modules are written."""


def ensure_dirs(*paths: Path) -> None:
    """Create the given directories (and parents) if they do not exist.

    Calling with no arguments creates the two directories every task relies
    on: :data:`RESULTS_DIR` and :data:`FIGURES_DIR`. This is the only
    side-effecting function in the module; the module-level constants stay
    pure.

    Parameters
    ----------
    *paths : pathlib.Path
        Directories to create. Defaults to ``(RESULTS_DIR, FIGURES_DIR)``.

    Examples
    --------
    >>> from bit2118.paths import ensure_dirs, RESULTS_DIR
    >>> ensure_dirs()                      # doctest: +SKIP
    >>> ensure_dirs(RESULTS_DIR / "custom")  # doctest: +SKIP
    """
    targets = paths or (RESULTS_DIR, FIGURES_DIR)
    for directory in targets:
        directory.mkdir(parents=True, exist_ok=True)
